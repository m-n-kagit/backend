import asyncHandler from "../utils/asynhandler.js"
import {ApiError} from "../utils/ApiError.js"
import { User} from "../models/user.models.js"
import {uploadCloudinery} from "../utils/cloudinary.js"
import {ApiResponse} from "../utils/ApiResponse.js"

const registerUser = asyncHandler(async(req,res)=>{
    //get user details from frontend validation
    //check if user already exists  : username , email
    //check for images, check for avatar
    //upload them to cloudinery, avatar    
    // create user object and save to database
    //remove password and refresh token field from response
    //check for user creation 
    //return res

    const  {fullname, email, username, password} =req.body
    console.log("email",email)
   if ([fullname, email, username , password].some((field)=> field?.trim === "")){ //alternative map function but it wants return anything 
    throw new ApiError(400, "fullname is required")
   }

   const existedUser = User.findOne({
    $or: [ { username }, { email }] //what attributes to be checked
   })

   if(existedUser){
    throw new ApiError(409,"User with email or username already exists")
   }

   const avatarLocalPath=req.files?.avatar[0]?.path;
   const coverImageLocalPath=req.files?.coverImage[0]?.path
   if(!avatarLocalPath){
        throw new ApiError(400,"Avatar file is required") //bad request       
    }

    const avatar = await uploadCloudinery(avatarLocalPath)
    
    if(!avatar){
        throw new ApiError(400,"Avatar file is required") //bad request       
    }

    const user = await User.create({ //entry in database
        fullname,
        avatar: avatar.url,
        coverImage : coverImage?.url || "",
        email,
        password,
        username: username.toLowerCase()
    })
    //_id field is automatically generated by mongodb 
    // and we can use it to find the user in database 
    // and return the response to frontend
    const created_user= await User.findById(user._id).select(
        "-password -refreshToken" //excluding pass and rf
    )
    if(!created_user){
        throw new ApiError(500, "Failed to create user")
    }

    return res.status(201).json(
        new ApiResponse(200, "User registered successfully", created_user)
    )
})

export default registerUser